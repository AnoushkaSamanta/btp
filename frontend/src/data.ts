export function getCopilotResponse(query: string): { text: string; sources: string[] } {
  const lower = query.toLowerCase();
  for (const key of Object.keys(copilotResponses)) {
    if (lower.includes(key)) {
      return copilotResponses[key];
    }
  }
  return {
    text: `I understand you are asking about "${query}". Based on GOI maternal health guidelines, I recommend checking the relevant protocol in the Resources section. For specific clinical decisions, always consult with the Medical Officer at your PHC. Would you like me to find a specific resource or guideline for this topic?`,
    sources: ['ASHA CoPilot Knowledge Base'],
  };
}

